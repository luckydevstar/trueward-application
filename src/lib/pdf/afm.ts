const parsed = new Map<Face, Map<string, number>>();

function widths(face: Face): Map<string, number> {
  let table = parsed.get(face);
  if (!table) {
    table = new Map();
    const { ascii, extra } = FACES[face];
    ascii.split(",").forEach((w, i) => table!.set(String.fromCharCode(32 + i), Number(w)));
    const extras = extra.split(",");
    [...EXTRA_CHARS].forEach((ch, i) => table!.set(ch, Number(extras[i])));
    parsed.set(face, table);
  }
  return table;
}

/**
 * The width of `text` in 1/1000 em, if `font` is Helvetica or Times; null for
 * any other font. A character outside the tables is measured by `fallback`.
 */
export function afmUnits(font: string, bold: boolean, text: string, fallback: (ch: string) => number): number | null {
  const family = font.toLowerCase();
  if (family !== "helvetica" && family !== "times") return null;
  const table = widths(`${family}${bold ? "Bold" : ""}` as Face);
  let units = 0;
  for (const ch of text) units += table.get(ch) ?? fallback(ch);
  return units;
}
