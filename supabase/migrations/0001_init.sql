-- ===========================================================================
-- Note on file storage
--
-- Uploaded bytes live in UploadThing, not in Supabase Storage, so there is no
-- bucket or storage.objects policy to define here. Access control for a file
-- is the resume_file row that points at it: the row is team-scoped by the
-- policies above, and the app only ever surfaces a file_url it read from a row
-- the caller was allowed to select.
--
-- Worth being clear about the limit of that: an UploadThing file URL is a
-- capability, not a session-checked resource. Anyone holding the URL can fetch
-- it. That matches how the previous project treated CV links, but if resumes
-- ever need to be unguessable-and-revocable, move them behind a route handler
-- that re-checks the row before streaming.
-- ===========================================================================
